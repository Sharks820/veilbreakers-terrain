@dataclass
class StochasticShaderTemplate:
    """Parameters describing a Heitz 2019 / Mikkelsen 2022 stochastic shader.

    Set ``tiling_mode="hex"`` to emit the Mikkelsen 2022 JCGT hex-tiling
    shader instead of the default Heitz 2019 triangular-basis variant.
    Hex-tiling eliminates the faint grid artifact visible in the triangular
    approach on low-frequency textures (e.g. sand, snow, mud).

    All fields are consumed by both the Python UV-offset bake
    (``build_stochastic_sampling_mask``) and the Unity HLSL shader template
    (``export_unity_shader_template``).

    Fields
    ------
    template_id : str
        Unique identifier embedded in the shader name.
    tile_size_m : float
        World-space size of one texture tile in metres.
    randomness_strength : float
        Per-tile UV offset scale in [0, 1].  0 = pure tiling (no breakup),
        1 = maximum Heitz-Neyret offset.
    histogram_preserving : bool
        If True, apply rank-based histogram equalisation to the UV offset
        channels so the output distribution is uniform across [-0.5, 0.5].
        This prevents the brightness drift caused by bilinear interpolation
        compressing offsets toward zero.
    contrast_correction : float
        Contrast expansion factor applied during histogram-preserving blend
        (Heitz 2019 Eq. 10).  Values > 1 expand contrast; 1.0 = identity.
        Typical range: 1.0–2.0.
    uv_rotation_range : float
        Maximum per-tile UV rotation in radians.  Rotated samples break up
        directional repetition artifacts (e.g. oriented rock grain).
        0.0 disables rotation; math.pi/4 (45°) is a typical AAA value.
    layer_index : int
        Which terrain layer index this template governs.
    notes : str
        Free-form human-readable notes.
    stochastic_seed : int
        Hash seed fed to the per-tile RNG in the HLSL shader.
    blend_sharpness : float
        Exponent of the triangular-basis blend kernel (Heitz 2019 Eq. 8).
        Higher values create sharper tile boundaries; 2.0 is the standard.
    blend_weights : List[float]
        Per-sample blend weights; must sum to 1.0.
    """

    template_id: str
    tile_size_m: float = 4.0
    randomness_strength: float = 0.75
    histogram_preserving: bool = True
    contrast_correction: float = 1.4
    uv_rotation_range: float = 0.0
    layer_index: int = 0
    notes: str = ""
    stochastic_seed: int = 0
    blend_sharpness: float = 2.0
    blend_weights: List[float] = field(default_factory=lambda: [1.0])
    tiling_mode: str = "triangular"  # "triangular" = Heitz 2019; "hex" = Mikkelsen 2022 JCGT

    _VALID_TILING_MODES = frozenset({"triangular", "hex"})

    def __post_init__(self) -> None:
        if self.tile_size_m <= 0.0:
            raise ValueError(f"tile_size_m must be > 0, got {self.tile_size_m}")
        if not (0.0 <= self.randomness_strength <= 1.0):
            raise ValueError(
                f"randomness_strength must be in [0, 1], got {self.randomness_strength}"
            )
        if self.blend_sharpness <= 0.0:
            raise ValueError(f"blend_sharpness must be > 0, got {self.blend_sharpness}")
        if self.contrast_correction <= 0.0:
            raise ValueError(f"contrast_correction must be > 0, got {self.contrast_correction}")
        if self.uv_rotation_range < 0.0:
            raise ValueError(f"uv_rotation_range must be >= 0, got {self.uv_rotation_range}")
        if not self.blend_weights:
            raise ValueError("blend_weights must be a non-empty list")
        total = sum(self.blend_weights)
        if abs(total - 1.0) > 1e-4:
            raise ValueError(
                f"blend_weights must sum to 1.0, got sum={total:.6f}"
            )
        if self.tiling_mode not in self._VALID_TILING_MODES:
            raise ValueError(
                f"tiling_mode must be one of {sorted(self._VALID_TILING_MODES)}, "
                f"got {self.tiling_mode!r}"
            )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "template_id": self.template_id,
            "tile_size_m": float(self.tile_size_m),
            "randomness_strength": float(self.randomness_strength),
            "histogram_preserving": bool(self.histogram_preserving),
            "contrast_correction": float(self.contrast_correction),
            "uv_rotation_range": float(self.uv_rotation_range),
            "layer_index": int(self.layer_index),
            "notes": self.notes,
            "stochastic_seed": int(self.stochastic_seed),
            "blend_sharpness": float(self.blend_sharpness),
            "blend_weights": [float(w) for w in self.blend_weights],
            "tiling_mode": self.tiling_mode,
        }


def _tile_hash_2d(tile_y: np.ndarray, tile_x: np.ndarray, seed: int) -> np.ndarray:
    """Hash (tile_y, tile_x) integer grid indices to a (N, 4) float32 array in [0,1].

    Uses a fast integer hash (Murmur3-inspired) that maps each (ty, tx) pair
    to 4 independent pseudo-random floats:
      col 0: u-offset channel
      col 1: v-offset channel
      col 2: rotation channel
      col 3: spare (contrast jitter, reserved)

    All four channels are independent.  Output is deterministic for fixed inputs.
    """
    # Flatten and pack into a single uint32 for hashing
    s = np.uint32(int(seed) & 0xFFFFFFFF)
    ty = tile_y.ravel().astype(np.uint32)
    tx = tile_x.ravel().astype(np.uint32)
    n = ty.size

    # Murmur3-inspired integer hash — four independent seeds per tile
    def _hash(a: np.ndarray, b: np.ndarray, k: np.uint32) -> np.ndarray:
        h = (a * np.uint32(2654435761)) ^ (b * np.uint32(2246822519)) ^ (s ^ k)
        h ^= h >> np.uint32(16)
        h *= np.uint32(0x45D9F3B)
        h ^= h >> np.uint32(16)
        return h.astype(np.float32) / np.float32(2 ** 32)

    out = np.empty((n, 4), dtype=np.float32)
    out[:, 0] = _hash(ty, tx, np.uint32(0))
    out[:, 1] = _hash(ty, tx, np.uint32(1))
    out[:, 2] = _hash(ty, tx, np.uint32(2))
    out[:, 3] = _hash(ty, tx, np.uint32(3))
    return out


def build_stochastic_sampling_mask(
    stack: TerrainMaskStack,
    tile_size_m: float,
    seed: int,
    coverage_fraction: float = 0.5,
    use_voronoi: bool = False,
    histogram_preserving: bool = True,
    uv_rotation_range: float = 0.0,
) -> np.ndarray:
    """Return a (H, W, 2) float32 UV-offset mask using Heitz 2019 per-tile hashing.

    Implementation follows Heitz & Neyret 2019 "Histogram-Preserving Blending":

    1. Divide the heightmap into a grid of texture tiles.
    2. For each tile cell, compute a deterministic hash → (u_offset, v_offset,
       rotation_angle) using a Murmur3-inspired integer hash of (tile_y, tile_x).
       This is the true Heitz/Neyret approach: hash-based per-tile random offsets
       rather than noise-based, giving perfectly uniform coverage with no
       spatial bias.
    3. Assign each heightmap pixel to its tile cell and look up the tile's offset.
    4. Apply UV rotation per tile (optional): rotate the UV offset vector by the
       tile's random rotation angle, breaking directional repetition in oriented
       textures such as rock grain and wood.
    5. If ``histogram_preserving=True``, apply rank-based equalisation to each
       channel so the output distribution is exactly uniform in [-0.5, 0.5],
       correcting the bilinear pull-toward-zero bias.

    Strategy B (``use_voronoi=True``):
      Same hash-based offsets but tile boundaries are hard (nearest-tile
      assignment, no interpolation), matching UE5's Voronoi stochastic node.

    Parameters
    ----------
    stack : TerrainMaskStack
        Must have ``height`` populated (shape/cell_size only).
    tile_size_m : float
        World-space size of one tileable texture tile in metres.
    seed : int
        Deterministic seed.
    coverage_fraction : float
        Unused in hash path; kept for API compatibility with fBm callers.
    use_voronoi : bool
        Hard-cell tile boundaries (no bilinear blend between tiles).
    histogram_preserving : bool
        Apply rank-based equalisation to UV channels.  Default True.
    uv_rotation_range : float
        Maximum per-tile rotation in radians (symmetric around 0).
        0.0 disables rotation.

    Returns
    -------
    np.ndarray
        Shape (H, W, 2), dtype float32.
        Channel 0 = U offset in [-0.5, 0.5].
        Channel 1 = V offset in [-0.5, 0.5].
    """
    if stack.height is None:
        raise ValueError("build_stochastic_sampling_mask requires stack.height")
    if tile_size_m <= 0.0:
        raise ValueError(f"tile_size_m must be > 0, got {tile_size_m}")
    if not (0.0 < coverage_fraction <= 1.0):
        raise ValueError(f"coverage_fraction must be in (0, 1], got {coverage_fraction}")

    h_arr = np.asarray(stack.height)
    rows, cols = h_arr.shape
    cell_m = float(stack.cell_size)

    # --- Per-pixel tile-index assignment -----------------------------------
    # Each pixel maps to a tile cell index (ty, tx).
    row_tile_f = np.arange(rows, dtype=np.float64) * cell_m / tile_size_m
    col_tile_f = np.arange(cols, dtype=np.float64) * cell_m / tile_size_m

    row_tile_idx = np.floor(row_tile_f).astype(np.int32)
    col_tile_idx = np.floor(col_tile_f).astype(np.int32)

    tiles_y = int(row_tile_idx.max()) + 2
    tiles_x = int(col_tile_idx.max()) + 2
    row_tile_idx = np.clip(row_tile_idx, 0, tiles_y - 1)
    col_tile_idx = np.clip(col_tile_idx, 0, tiles_x - 1)

    # --- Build hash table for every tile cell ----------------------------
    # Shape: (tiles_y * tiles_x, 4)
    ty_grid, tx_grid = np.mgrid[0:tiles_y, 0:tiles_x]
    hash_vals = _tile_hash_2d(ty_grid.ravel(), tx_grid.ravel(), int(seed) & 0xFFFFFFFF)
    # Reshape to (tiles_y, tiles_x, 4)
    hash_grid = hash_vals.reshape(tiles_y, tiles_x, 4)

    # UV offsets: map [0,1] hash → [-0.5, 0.5]
    tile_u = (hash_grid[..., 0] - 0.5).astype(np.float32)
    tile_v = (hash_grid[..., 1] - 0.5).astype(np.float32)
    tile_r = (hash_grid[..., 2] - 0.5).astype(np.float32) * float(uv_rotation_range)

    if use_voronoi:
        # Hard-cell: each pixel gets the exact offset of its owning tile
        u = tile_u[np.ix_(row_tile_idx, col_tile_idx)]
        v = tile_v[np.ix_(row_tile_idx, col_tile_idx)]
        rot = tile_r[np.ix_(row_tile_idx, col_tile_idx)] if uv_rotation_range > 0 else None
    else:
        # Smooth: bilinearly interpolate between tile corners for continuity
        ty_f = row_tile_f - row_tile_idx.astype(np.float64)   # frac in [0,1)
        tx_f = col_tile_f - col_tile_idx.astype(np.float64)

        y0 = row_tile_idx
        x0 = col_tile_idx
        y1 = np.clip(y0 + 1, 0, tiles_y - 1)
        x1 = np.clip(x0 + 1, 0, tiles_x - 1)
        wy = ty_f.reshape(-1, 1).astype(np.float32)
        wx = tx_f.reshape(1, -1).astype(np.float32)

        def _bilerp(g: np.ndarray) -> np.ndarray:
            a = g[np.ix_(y0, x0)]
            b = g[np.ix_(y0, x1)]
            c = g[np.ix_(y1, x0)]
            d = g[np.ix_(y1, x1)]
            return (a * (1 - wx) + b * wx) * (1 - wy) + (c * (1 - wx) + d * wx) * wy

        u = _bilerp(tile_u)
        v = _bilerp(tile_v)
        rot = _bilerp(tile_r) if uv_rotation_range > 0 else None

    # --- UV rotation: rotate (u, v) by per-tile angle -------------------
    if rot is not None:
        cos_r = np.cos(rot).astype(np.float32)
        sin_r = np.sin(rot).astype(np.float32)
        u_rot = cos_r * u - sin_r * v
        v_rot = sin_r * u + cos_r * v
        u = u_rot
        v = v_rot

    result = np.stack([u, v], axis=-1).astype(np.float32)

    # --- Histogram-preserving equalisation (Heitz 2019 Eq. 10) ----------
    # Rank-remap each channel to a uniform distribution in [-0.5, 0.5].
    # This corrects the bilinear pull-toward-zero that would otherwise cause
    # visible brightness drift in tiled PBR textures.
    if histogram_preserving:
        for ch in range(2):
            chan = result[..., ch].ravel()
            n = chan.size
            rank = np.empty(n, dtype=np.float32)
            order = np.argsort(chan)
            rank[order] = np.linspace(-0.5, 0.5, n, dtype=np.float32)
            result[..., ch] = rank.reshape(result.shape[:2])

    return result


