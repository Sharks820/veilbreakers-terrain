def build_hex_tiling_mask(
    stack: "TerrainMaskStack",
    tile_size_m: float,
    seed: int,
    histogram_preserving: bool = True,
    uv_rotation_range: float = 0.0,
) -> np.ndarray:
    """Return a (H, W, 2) float32 UV-offset mask using Mikkelsen 2022 hex-tiling.

    Implements the Python CPU-bake equivalent of the hex HLSL shader (Section 3
    of Mikkelsen 2022 JCGT Vol. 11 No. 3).  Each texel gets the blend-weighted
    average UV offset of its three surrounding hex centers, removing the faint
    axis-aligned grid artifact produced by the triangular Heitz 2019 approach.

    The hex lattice uses a 60°-skewed coordinate system:
      RectToHex = [[1, -1/√3], [0, 2/√3]]
      HexToRect = [[1, 1/2],   [0, √3/2]]

    For each pixel p in UV space:
      1. hp = RectToHex · (p / tile_size_m)
      2. ip = floor(hp);  fp = hp - ip
      3. Two triangle candidates (fp.x + fp.y < 1 or ≥ 1)
      4. w = pow4 smooth weights → normalised
      5. offset = weighted average of hash offsets at 3 hex centers

    Parameters
    ----------
    stack : TerrainMaskStack
        Must have ``height`` populated (shape / cell_size only).
    tile_size_m : float
        World-space size of one tileable texture tile in metres.
    seed : int
        Deterministic seed.
    histogram_preserving : bool
        Rank-equalise each channel to a uniform distribution in [-0.5, 0.5].
    uv_rotation_range : float
        Maximum per-tile rotation in radians (0 = no rotation).

    Returns
    -------
    np.ndarray  shape (H, W, 2), dtype float32.
        Channel 0 = U offset in [-0.5, 0.5].
        Channel 1 = V offset in [-0.5, 0.5].
    """
    import math as _math

    if stack.height is None:
        raise ValueError("build_hex_tiling_mask requires stack.height")
    if tile_size_m <= 0.0:
        raise ValueError(f"tile_size_m must be > 0, got {tile_size_m}")

    h_arr = np.asarray(stack.height)
    rows, cols = h_arr.shape
    cell_m = float(stack.cell_size)

    # World-space UV coordinates for each pixel (tile-normalised)
    pu = np.arange(cols, dtype=np.float32) * cell_m / tile_size_m   # (W,)
    pv = np.arange(rows, dtype=np.float32) * cell_m / tile_size_m   # (H,)

    # Hex transform: RectToHex = [[1, -1/sqrt(3)], [0, 2/sqrt(3)]]
    inv_sqrt3 = np.float32(1.0 / _math.sqrt(3.0))
    two_over_sqrt3 = np.float32(2.0 / _math.sqrt(3.0))

    # hp = RectToHex @ [u, v]:  hp_u = u - v/sqrt(3);  hp_v = v * 2/sqrt(3)
    pu_g, pv_g = np.meshgrid(pu, pv)  # both (H, W)
    hp_u = pu_g - pv_g * inv_sqrt3
    hp_v = pv_g * two_over_sqrt3

    # Integer hex cell and fractional position
    ip_u = np.floor(hp_u).astype(np.int32)
    ip_v = np.floor(hp_v).astype(np.int32)
    fp_u = (hp_u - ip_u).astype(np.float32)
    fp_v = (hp_v - ip_v).astype(np.float32)

    # HexToRect = [[1, 0.5], [0, sqrt(3)/2]]
    half = np.float32(0.5)
    sqrt3_over2 = np.float32(_math.sqrt(3.0) / 2.0)

    def _hex_to_rect_u(hu: np.ndarray, hv: np.ndarray) -> np.ndarray:
        return hu.astype(np.float32) + hv.astype(np.float32) * half

    def _hex_to_rect_v(hv: np.ndarray) -> np.ndarray:
        return hv.astype(np.float32) * sqrt3_over2

    # Murmur3-inspired float hash for 2D hex center → (u_off, v_off, rot)
    s = np.uint32(int(seed) & 0xFFFFFFFF)

    def _hash_hex(hu: np.ndarray, hv: np.ndarray, k: np.uint32) -> np.ndarray:
        a = hu.ravel().astype(np.int32).view(np.uint32)
        b = hv.ravel().astype(np.int32).view(np.uint32)
        h = (a * np.uint32(2654435761)) ^ (b * np.uint32(2246822519)) ^ (s ^ k)
        h ^= h >> np.uint32(16)
        h *= np.uint32(0x45D9F3B)
        h ^= h >> np.uint32(16)
        return (h.astype(np.float64) / float(2 ** 32)).reshape(hu.shape).astype(np.float32)

    # Determine triangle case per pixel (vectorised)
    case_hi = (fp_u + fp_v) >= 1.0  # True = upper triangle

    # Hex center indices for the 3 candidates (each (H,W))
    h1u = np.where(case_hi, ip_u + 1, ip_u).astype(np.int32)
    h1v = np.where(case_hi, ip_v + 1, ip_v).astype(np.int32)
    h2u = ip_u.astype(np.int32)
    h2v = (ip_v + 1).astype(np.int32)
    h3u = (ip_u + 1).astype(np.int32)
    h3v = ip_v.astype(np.int32)

    # Blend weights (power-4 smooth, normalised)
    w1 = np.where(case_hi, fp_u + fp_v - 1.0, 1.0 - fp_u - fp_v).astype(np.float32)
    w2 = np.where(case_hi, 1.0 - fp_u, fp_v).astype(np.float32)
    w3 = np.where(case_hi, 1.0 - fp_v, fp_u).astype(np.float32)
    w1 = np.clip(w1, 0.0, 1.0) ** 4
    w2 = np.clip(w2, 0.0, 1.0) ** 4
    w3 = np.clip(w3, 0.0, 1.0) ** 4
    w_sum = w1 + w2 + w3 + np.float32(1e-6)
    w1 /= w_sum
    w2 /= w_sum
    w3 /= w_sum

    # Per-hex-center hash offsets in [-0.5, 0.5]
    ou1 = _hash_hex(h1u, h1v, np.uint32(0)) - 0.5
    ov1 = _hash_hex(h1u, h1v, np.uint32(1)) - 0.5
    ou2 = _hash_hex(h2u, h2v, np.uint32(0)) - 0.5
    ov2 = _hash_hex(h2u, h2v, np.uint32(1)) - 0.5
    ou3 = _hash_hex(h3u, h3v, np.uint32(0)) - 0.5
    ov3 = _hash_hex(h3u, h3v, np.uint32(1)) - 0.5

    # Weighted blend of offsets
    u = w1 * ou1 + w2 * ou2 + w3 * ou3
    v = w1 * ov1 + w2 * ov2 + w3 * ov3

    # Optional UV rotation (blend-weighted angle)
    if uv_rotation_range > 0.0:
        r1 = (_hash_hex(h1u, h1v, np.uint32(2)) - 0.5) * float(uv_rotation_range)
        r2 = (_hash_hex(h2u, h2v, np.uint32(2)) - 0.5) * float(uv_rotation_range)
        r3 = (_hash_hex(h3u, h3v, np.uint32(2)) - 0.5) * float(uv_rotation_range)
        rot = (w1 * r1 + w2 * r2 + w3 * r3).astype(np.float32)
        cos_r = np.cos(rot).astype(np.float32)
        sin_r = np.sin(rot).astype(np.float32)
        u_rot = cos_r * u - sin_r * v
        v_rot = sin_r * u + cos_r * v
        u, v = u_rot, v_rot

    result = np.stack([u, v], axis=-1).astype(np.float32)

    if histogram_preserving:
        for ch in range(2):
            chan = result[..., ch].ravel()
            n = chan.size
            rank = np.empty(n, dtype=np.float32)
            order = np.argsort(chan)
            rank[order] = np.linspace(-0.5, 0.5, n, dtype=np.float32)
            result[..., ch] = rank.reshape(result.shape[:2])

    return result


